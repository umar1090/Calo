/**
 * Generates supabase/seed.sql from the app's Indian food database so the
 * Supabase `foods` table and the bundled data stay identical.
 *
 *   npm run seed:sql
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { FOODS } from '../src/data/foods';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);

export function foodSeedSql(): string {
  const rows = FOODS.map((f) =>
    [
      q(f.id), 'null', q(f.name), arr(f.aliases), q(f.category), `${q(f.diet)}::public.food_diet`, String(f.rootVeg), arr(f.allergens), arr(f.groups),
      f.vegFraction, f.fruitFraction, f.per100.kcal, f.per100.protein, f.per100.carbs, f.per100.fat, f.per100.fiber,
      `${q(JSON.stringify(f.portions))}::jsonb`, q(f.defaultPortionId), q(f.unit), String(f.homemade), String(f.oilAdjustable), arr(f.meals), arr(f.cuisines), f.cost,
    ].join(', '),
  );
  return `-- Generated by scripts/generate-food-seed.ts. Do not edit by hand.
insert into public.foods (id, owner_id, name, aliases, category, diet, root_veg, allergens, food_groups, veg_fraction, fruit_fraction,
  kcal_per_100, protein_per_100, carbs_per_100, fat_per_100, fiber_per_100, portions, default_portion_id, unit, homemade, oil_adjustable, meals, cuisines, cost)
values
${rows.map((r) => `  (${r})`).join(',\n')}
on conflict (id) do update set
  name = excluded.name, aliases = excluded.aliases, category = excluded.category, diet = excluded.diet, root_veg = excluded.root_veg,
  allergens = excluded.allergens, food_groups = excluded.food_groups, veg_fraction = excluded.veg_fraction, fruit_fraction = excluded.fruit_fraction,
  kcal_per_100 = excluded.kcal_per_100, protein_per_100 = excluded.protein_per_100, carbs_per_100 = excluded.carbs_per_100,
  fat_per_100 = excluded.fat_per_100, fiber_per_100 = excluded.fiber_per_100, portions = excluded.portions,
  default_portion_id = excluded.default_portion_id, unit = excluded.unit, homemade = excluded.homemade,
  oil_adjustable = excluded.oil_adjustable, meals = excluded.meals, cuisines = excluded.cuisines, cost = excluded.cost;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = new URL('../supabase/seed.sql', import.meta.url);
  writeFileSync(out, foodSeedSql());
  console.log(`Wrote ${FOODS.length} foods to ${fileURLToPath(out)}`);
}
